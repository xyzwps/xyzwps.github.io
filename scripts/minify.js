#!/usr/bin/env node
/**
 * scripts/minify.js — 构建期压缩 HTML / CSS
 *
 *   node scripts/minify.js dist
 *
 * 压缩本身交给现成的库，脚本只负责遍历 dist：
 *   - HTML: html-minifier-terser（保留 pre/code/textarea/script，内联 CSS 一起压）
 *   - CSS:  clean-css（level 1，只做安全优化，不做规则重排）
 *
 * 只改 dist，源文件保持可读；跳过 tools/（已构建的单文件编辑器）
 * 和 pages/site.html（它其实是纯文本 URL 清单）。
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const CleanCSS = require('clean-css');
const { minify: minifyMarkup } = require('html-minifier-terser');

const cleanCss = new CleanCSS({ level: 1 });

const HTML_OPTIONS = {
  collapseWhitespace: true,
  removeComments: true,
  minifyCSS: { level: 1 },
  minifyJS: false,
  caseSensitive: true,
  keepClosingSlash: true,
  decodeEntities: false,
  removeAttributeQuotes: false,
  removeOptionalTags: false,
  collapseBooleanAttributes: false,
  removeEmptyAttributes: false,
  removeRedundantAttributes: false,
  sortAttributes: false,
  sortClassName: false,
  includeAutoGeneratedTags: false,
};

function minifyCss(source, file) {
  const result = cleanCss.minify(source);
  if (result.errors.length > 0) {
    throw new Error(`${file}: ${result.errors.join('; ')}`);
  }
  return result.styles;
}

async function minifyHtml(source, file) {
  try {
    return await minifyMarkup(source, HTML_OPTIONS);
  } catch (error) {
    throw new Error(`${file}: ${error.message}`);
  }
}

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'tools') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else files.push(full);
  }
  return files;
}

function formatBytes(bytes) {
  return bytes >= 1024 ? `${(bytes / 1024).toFixed(1)}K` : `${bytes}B`;
}

async function main() {
  const root = path.resolve(process.argv[2] || 'dist');
  if (!fs.existsSync(root)) {
    console.error(`minify: 目录不存在: ${root}`);
    process.exit(1);
  }

  let before = 0;
  let after = 0;
  let count = 0;

  for (const file of walk(root).sort()) {
    const ext = path.extname(file).toLowerCase();
    if (ext !== '.html' && ext !== '.css') continue;

    const source = fs.readFileSync(file, 'utf8');

    // site.html 其实是几行纯文本，别把它当 HTML 压。
    if (ext === '.html' && !/<html[\s>]/i.test(source) && !/<!doctype/i.test(source)) {
      continue;
    }

    const minified =
      ext === '.css'
        ? minifyCss(source, path.relative(root, file))
        : await minifyHtml(source, path.relative(root, file));

    const beforeSize = Buffer.byteLength(source);
    const afterSize = Buffer.byteLength(minified);

    before += beforeSize;
    after += afterSize;
    count += 1;

    if (minified !== source) fs.writeFileSync(file, minified);
    const saved = beforeSize ? (1 - afterSize / beforeSize) * 100 : 0;
    console.log(
      `  minify  ${path.relative(root, file).padEnd(28)} ` +
        `${formatBytes(beforeSize).padStart(6)} → ${formatBytes(afterSize).padStart(6)}  ` +
        `-${saved.toFixed(0)}%`,
    );
  }

  const saved = before ? ((1 - after / before) * 100).toFixed(1) : '0.0';
  console.log(`\n  minify  ${count} 个文件，${formatBytes(before)} → ${formatBytes(after)}（-${saved}%）\n`);
}

main().catch((error) => {
  console.error(`minify: ${error.message}`);
  process.exit(1);
});
